"""Журнал Python для встроенного Cubit в Fidesys 10.0. Запускать в пустой модели."""
from typing import List, Tuple

import cubit  # type: ignore[import-not-found]


def segment(start: Tuple[float, float], end: Tuple[float, float]) -> None:
    for x, y in (start, end):
        cubit.cmd(f"create vertex {x} {y} 0")
    last = cubit.get_last_id("vertex")
    cubit.cmd(f"create curve vertex {last - 1} {last}")


def spline(poles: List[Tuple[float, float]], knots: List[float]) -> None:
    xyz = [value for x, y in poles for value in (x, y, 0.0)]
    # Cubit принимает узловой вектор без первого и последнего повторений.
    curve_id = cubit.create_nurbs_curve(3, xyz, [1.0] * len(poles), knots[1:-1])
    if curve_id <= 0:
        raise RuntimeError("Ошибка создания B-сплайна")


