""" ### Контроль порядка и шага по времени на ECVB12404 ### """

"""
На каждой из двух фиксированных Q2-сеток сравнивали соседние порядки при одинаковом временном шаге внутри пары. За опору брали решение старшего порядка. Отдельно при p4 вдвое уменьшили шаг по времени, взяв за опору расчёт с меньшим шагом. Таблица даёт минимум и максимум относительной разности в процентах по двум компонентам и обеим геометриям. Это исходная серия контроля на CPU.
"""

metrics = mapping(read_json(data / "pilot_runs/comparison/metrics.json")["metrics"])
records = {str(record["name"]): record for record in map(mapping, sequence(metrics["records"]))}
rows = ["| Проверка | Запись 0–2 с, % | Кода 1–2 с, % | Поле при 2 с, % |", "|---|---:|---:|---:|"]
for label, transition, digits in (
    ("p2 → p3", "p2 to p3", 2),
    ("p3 → p4", "p3 to p4", 2),
    ("p4 → p5", "p4 s36 to p5 s36", 2),
    ("Δt → Δt/2 при p4", "p4 s18 to s36 temporal", 4),
):
    full_values: list[float] = []
    late_values: list[float] = []
    field_values: list[float] = []
    for geometry in ("raster", "curved"):
        record = records[f"{geometry}: {transition}"]
        surface = mapping(record["surface"])
        windows = map(mapping, sequence(surface["time_windows"]))
        late = next(window for window in windows if pair(window["time_window_s"]) == (1.0, 2.0))
        fields = map(mapping, sequence(record["fields"]))
        final = next(field for field in fields if field["time_s"] == 2.0)
        full_values.extend(pair(surface["all_surface"]))
        late_values.extend(pair(late["relative_l2"]))
        field_values.extend(pair(final["relative_l2"]))
    ranges = [f"{percent(min(values), digits)}–{percent(max(values), digits)}" for values in (full_values, late_values, field_values)]
    rows.append("| " + " | ".join([label, *ranges]) + " |")
display(Markdown("\n".join(rows)))

"""
На растре переход p4 → p5 меняет полную запись на 0,152% по Ux и 0,106% по Uy, уменьшение шага вдвое при p4 — на 0,0034% и 0,0029%. В презентации p3 рассматривался как кандидат для массовой серии при 15 Гц. Для измерения малых различий между геометриями использованы p4 и p5.

Чтобы оценить, разрешён ли эффект сглаживания, норму разности двух решений при p5 делили на сумму норм поправок p4 → p5 для растровой и гладкой сеток. В позднем окне отношение составило 109,60 для Ux и 65,01 для Uy. Для всей записи получено лишь 2,76 и 2,40 при принятом в протоколе пороге 5. Эта проверка относится к №12404.
"""

